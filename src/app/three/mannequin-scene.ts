import * as THREE from 'three';
import { OrbitControls } from 'three/examples/jsm/controls/OrbitControls.js';
import { RoomEnvironment } from 'three/examples/jsm/environments/RoomEnvironment.js';
import { THREE_ASSETS } from '../core/config/three-assets.config';
import { MeasurementDefinition } from '../models/measurement.model';
import { loadModel } from './model-loader';
import { createProceduralMannequin } from './procedural-mannequin';
import { buildRibbon, disposeObject, dotTexture, radialShadowTexture } from './three-utils';

export interface MannequinSceneOptions {
  quality: 'high' | 'low';
  pixelRatio: number;
  reducedMotion: boolean;
}

export interface LabelPosition {
  x: number;
  y: number;
  visible: boolean;
}

interface Indicator {
  def: MeasurementDefinition;
  points: THREE.Vector3[];
  tape: THREE.Mesh;
  ghost: THREE.Mesh;
  markers: THREE.Object3D[];
  anchor: THREE.Vector3;
  anchorNormal: THREE.Vector3;
  indexCount: number;
}

const RED = 0xe32126;

/**
 * Measurement-guide scene: neutral mannequin + measuring-tape indicators.
 * Indicators are generated by raycasting the mannequin surface, so they work for
 * the procedural mannequin AND for any replacement GLB model.
 */
export class MannequinScene {
  onLabel?: (pos: LabelPosition) => void;

  private readonly renderer: THREE.WebGLRenderer;
  private readonly scene = new THREE.Scene();
  private readonly camera = new THREE.PerspectiveCamera(32, 1, 0.1, 50);
  private controls!: OrbitControls;
  private pmrem?: THREE.PMREMGenerator;
  private envTex?: THREE.Texture;
  private readonly indicators = new Map<string, Indicator>();
  private readonly defs = new Map<string, MeasurementDefinition>();
  private activeId: string | null = null;
  private active: Indicator | null = null;
  private progress = 1;
  private pulse!: THREE.Sprite;
  private bounds = new THREE.Box3();
  private baseDistance = 6;
  private camTarget: { az: number; el: number; dist: number; ty: number } | null = null;
  private readonly spherical = new THREE.Spherical();
  private frame = 0;
  private running = false;
  private readonly clock = new THREE.Timer();
  private resizeObserver?: ResizeObserver;
  private tapeTexture?: THREE.CanvasTexture;

  constructor(
    private readonly canvas: HTMLCanvasElement,
    private readonly opts: MannequinSceneOptions,
  ) {
    this.renderer = new THREE.WebGLRenderer({ canvas, antialias: true, alpha: true });
    this.renderer.setPixelRatio(opts.pixelRatio);
    this.renderer.toneMapping = THREE.ACESFilmicToneMapping;
    this.renderer.toneMappingExposure = 1.0;
    this.renderer.outputColorSpace = THREE.SRGBColorSpace;
    this.renderer.setClearColor(0x000000, 0);
  }

  async init(defs: MeasurementDefinition[]): Promise<void> {
    this.pmrem = new THREE.PMREMGenerator(this.renderer);
    this.envTex = this.pmrem.fromScene(new RoomEnvironment(), 0.04).texture;
    this.scene.environment = this.envTex;
    this.scene.environmentIntensity = 0.45;

    this.scene.add(new THREE.HemisphereLight(0xffffff, 0x222222, 0.6));
    const key = new THREE.DirectionalLight(0xfff4ea, 2.4);
    key.position.set(2.5, 3, 4);
    const rim = new THREE.DirectionalLight(0xdde4ff, 1.6);
    rim.position.set(-3, 2, -3);
    const red = new THREE.PointLight(RED, 6, 8, 1.5);
    red.position.set(-2.5, 0.5, -1.5);
    this.scene.add(key, rim, red);

    const { object } = await loadModel(THREE_ASSETS.mannequin, () =>
      createProceduralMannequin(this.opts.quality),
    );
    this.scene.add(object);
    object.updateMatrixWorld(true);

    const measurable: THREE.Mesh[] = [];
    object.traverse((o) => {
      const mesh = o as THREE.Mesh;
      if (!mesh.isMesh) return;
      const flagged =
        object.name === 'ProceduralMannequin'
          ? mesh.userData['measurable']
          : !/stand|base|pole/i.test(mesh.name);
      if (flagged) measurable.push(mesh);
    });
    this.bounds = new THREE.Box3();
    measurable.forEach((m) => this.bounds.expandByObject(m));

    const fullBounds = new THREE.Box3().setFromObject(object);
    const shadow = new THREE.Mesh(
      new THREE.PlaneGeometry(2.4, 2.4),
      new THREE.MeshBasicMaterial({
        map: radialShadowTexture(),
        transparent: true,
        depthWrite: false,
        opacity: 0.7,
      }),
    );
    shadow.rotation.x = -Math.PI / 2;
    shadow.position.y = fullBounds.min.y + 0.002;
    this.scene.add(shadow);

    this.tapeTexture = this.createTapeTexture();
    for (const def of defs) {
      this.defs.set(def.id, def);
      const ind = this.buildIndicator(def, measurable);
      if (ind) this.indicators.set(def.id, ind);
    }

    this.pulse = new THREE.Sprite(
      new THREE.SpriteMaterial({
        map: dotTexture(),
        color: 0xff4d52,
        blending: THREE.AdditiveBlending,
        depthTest: false,
        transparent: true,
      }),
    );
    this.pulse.scale.setScalar(0.12);
    this.pulse.visible = false;
    this.scene.add(this.pulse);

    this.controls = new OrbitControls(this.camera, this.canvas);
    this.controls.enableZoom = false;
    this.controls.enablePan = false;
    this.controls.enableDamping = true;
    this.controls.dampingFactor = 0.08;
    this.controls.rotateSpeed = 0.6;
    this.controls.minPolarAngle = Math.PI * 0.3;
    this.controls.maxPolarAngle = Math.PI * 0.62;
    this.controls.addEventListener('start', () => (this.camTarget = null));

    this.resize();
    const first = defs[0];
    if (first) this.jumpCamera(first);
    this.resizeObserver = new ResizeObserver(() => this.resize());
    this.resizeObserver.observe(this.canvas.parentElement ?? this.canvas);
    this.render(0);
  }

  // -------------------------------------------------------------------------

  private createTapeTexture(): THREE.CanvasTexture {
    const c = document.createElement('canvas');
    c.width = 256;
    c.height = 32;
    const ctx = c.getContext('2d')!;
    ctx.fillStyle = '#e32126';
    ctx.fillRect(0, 0, 256, 32);
    ctx.fillStyle = 'rgba(255,255,255,0.92)';
    for (let i = 0; i < 40; i++) {
      const x = i * 6.4;
      const h = i % 10 === 0 ? 18 : i % 5 === 0 ? 12 : 7;
      ctx.fillRect(x, 0, 1.4, h);
    }
    ctx.fillStyle = 'rgba(0,0,0,0.25)';
    ctx.fillRect(0, 30, 256, 2);
    const t = new THREE.CanvasTexture(c);
    t.wrapS = THREE.RepeatWrapping;
    t.colorSpace = THREE.SRGBColorSpace;
    t.anisotropy = 4;
    return t;
  }

  private heightAt(ratio: number): number {
    return this.bounds.min.y + ratio * (this.bounds.max.y - this.bounds.min.y);
  }

  /** Cast a horizontal ray towards the vertical axis at angle `theta`, return surface point + normal. */
  private probe(meshes: THREE.Mesh[], y: number, theta: number, ray: THREE.Raycaster) {
    const center = this.bounds.getCenter(new THREE.Vector3());
    const dir = new THREE.Vector3(Math.sin(theta), 0, Math.cos(theta));
    ray.set(new THREE.Vector3(center.x, y, center.z).addScaledVector(dir, 6), dir.clone().negate());
    const hit = ray.intersectObjects(meshes, true)[0];
    if (!hit) return null;
    const n = hit.face
      ? hit.face.normal
          .clone()
          .applyNormalMatrix(new THREE.Matrix3().getNormalMatrix(hit.object.matrixWorld))
          .normalize()
      : dir.clone();
    if (n.dot(dir) < 0) n.negate();
    return { p: hit.point.clone(), n };
  }

  private buildIndicator(def: MeasurementDefinition, meshes: THREE.Mesh[]): Indicator | null {
    const ray = new THREE.Raycaster();
    const points: THREE.Vector3[] = [];
    const normals: THREE.Vector3[] = [];
    const g = def.guide3d;
    if (!g) return null;

    if (g.kind === 'ring') {
      const y = this.heightAt(g.heightRatio);
      const N = 120;
      for (let i = 0; i <= N; i++) {
        const hit = this.probe(meshes, y, (i / N) * Math.PI * 2, ray);
        if (hit) {
          points.push(hit.p);
          normals.push(hit.n);
        }
      }
    } else {
      const N = 70;
      const y0 = this.heightAt(g.fromRatio);
      const y1 = this.heightAt(g.toRatio);
      for (let i = 0; i <= N; i++) {
        const hit = this.probe(meshes, y0 + ((y1 - y0) * i) / N, g.angle, ray);
        if (hit) {
          points.push(hit.p);
          normals.push(hit.n);
        }
      }
    }
    if (points.length < 4) return null;

    const sides = points.map((p, i) => {
      const next = points[Math.min(points.length - 1, i + 1)];
      const prev = points[Math.max(0, i - 1)];
      const tangent = next.clone().sub(prev).normalize();
      return new THREE.Vector3().crossVectors(tangent, normals[i]).normalize();
    });

    const { geometry, length } = buildRibbon(points, sides, normals, 0.05, 0.008);
    const tex = this.tapeTexture!.clone();
    tex.repeat.set(1 / 0.32, 1);
    tex.needsUpdate = true;
    const tape = new THREE.Mesh(
      geometry,
      new THREE.MeshStandardMaterial({
        map: tex,
        roughness: 0.55,
        emissive: new THREE.Color(RED),
        emissiveIntensity: 0.35,
        side: THREE.DoubleSide,
        polygonOffset: true,
        polygonOffsetFactor: -2,
      }),
    );
    tape.visible = false;
    tape.renderOrder = 2;

    const ghostGeo = buildRibbon(points, sides, normals, 0.012, 0.006).geometry;
    const ghost = new THREE.Mesh(
      ghostGeo,
      new THREE.MeshBasicMaterial({
        color: 0x5a5753,
        transparent: true,
        opacity: 0.55,
        side: THREE.DoubleSide,
      }),
    );

    const markers: THREE.Object3D[] = [];
    const markerMat = new THREE.MeshStandardMaterial({
      color: 0xffffff,
      emissive: RED,
      emissiveIntensity: 0.6,
    });
    const ends = g.kind === 'vertical' ? [0, points.length - 1] : [0];
    for (const i of ends) {
      const m = new THREE.Mesh(new THREE.SphereGeometry(0.028, 16, 12), markerMat);
      m.position.copy(points[i]).addScaledVector(normals[i], 0.02);
      m.visible = false;
      markers.push(m);
      this.scene.add(m);
    }

    // Label anchor: for rings the point facing the camera's side; for vertical lines the middle.
    let ai = Math.floor(points.length / 2);
    if (g.kind === 'ring') {
      const theta = def.camera.azimuth + 0.75;
      ai = Math.round(((((theta / (Math.PI * 2)) % 1) + 1) % 1) * (points.length - 1));
    }
    this.scene.add(tape, ghost);
    void length;
    return {
      def,
      points,
      tape,
      ghost,
      markers,
      anchor: points[ai].clone().addScaledVector(normals[ai], 0.05),
      anchorNormal: normals[ai].clone(),
      indexCount: geometry.getIndex()!.count,
    };
  }

  // -------------------------------------------------------------------------

  setActive(id: string): void {
    const ind = this.indicators.get(id) ?? null;
    const def = this.defs.get(id);
    if (this.active === ind && (ind || this.activeId === id)) return;
    this.activeId = id;
    if (this.active) {
      this.active.tape.visible = false;
      this.active.ghost.visible = true;
      this.active.markers.forEach((m) => (m.visible = false));
    }
    this.active = ind;
    if (!ind) {
      // nothing to draw on the torso (e.g. body height) — just reframe
      this.onLabel?.({ x: 0, y: 0, visible: false });
      if (def) this.moveCamera(def);
      return;
    }
    ind.ghost.visible = false;
    ind.tape.visible = true;
    this.progress = this.opts.reducedMotion ? 1 : 0;
    this.applyProgress();
    this.moveCamera(ind.def);
  }

  private orbitFor(def: MeasurementDefinition) {
    const c = def.camera;
    return {
      az: c.azimuth,
      el: c.elevation,
      dist: this.baseDistance * c.distance,
      ty: this.heightAt(c.targetRatio),
    };
  }

  private moveCamera(def: MeasurementDefinition): void {
    this.camTarget = this.orbitFor(def);
    if (this.opts.reducedMotion) this.jumpCamera(def);
  }

  private jumpCamera(def: MeasurementDefinition): void {
    const o = this.orbitFor(def);
    this.controls.target.set(0, o.ty, 0);
    this.spherical.set(o.dist, Math.PI / 2 - o.el, o.az);
    this.camera.position.setFromSpherical(this.spherical).add(this.controls.target);
    this.camera.lookAt(this.controls.target);
    this.camTarget = null;
  }

  private applyProgress(): void {
    if (!this.active) return;
    const p = this.progress;
    const eased = p < 0.5 ? 2 * p * p : 1 - Math.pow(-2 * p + 2, 2) / 2;
    const count = Math.floor((this.active.indexCount / 6) * eased) * 6;
    this.active.tape.geometry.setDrawRange(0, count);
    this.active.markers.forEach((m, i) => (m.visible = i === 0 ? p > 0.02 : p >= 1));
  }

  private resize(): void {
    const el = this.canvas.parentElement ?? this.canvas;
    const w = el.clientWidth;
    const h = el.clientHeight;
    if (!w || !h) return;
    this.renderer.setSize(w, h, false);
    this.camera.aspect = w / h;
    this.camera.updateProjectionMatrix();
    const height = this.bounds.max.y - this.bounds.min.y || 2;
    const fit = (height * 0.62) / Math.tan(THREE.MathUtils.degToRad(this.camera.fov / 2));
    this.baseDistance = fit * (this.camera.aspect < 0.8 ? 0.8 / this.camera.aspect : 1);
  }

  start(): void {
    if (this.running) return;
    this.running = true;
    this.clock.update();
    const loop = () => {
      if (!this.running) return;
      this.clock.update();
      this.render(this.clock.getDelta());
      this.frame = requestAnimationFrame(loop);
    };
    this.frame = requestAnimationFrame(loop);
  }

  stop(): void {
    this.running = false;
    cancelAnimationFrame(this.frame);
  }

  private readonly tmp = new THREE.Vector3();

  private render(dt: number): void {
    // camera glide toward the active step's framing
    if (this.camTarget) {
      const k = 1 - Math.pow(0.002, dt);
      const t = this.camTarget;
      this.controls.target.y += (t.ty - this.controls.target.y) * k;
      this.spherical.setFromVector3(this.tmp.copy(this.camera.position).sub(this.controls.target));
      let dAz = t.az - this.spherical.theta;
      dAz = Math.atan2(Math.sin(dAz), Math.cos(dAz));
      this.spherical.theta += dAz * k;
      this.spherical.phi += (Math.PI / 2 - t.el - this.spherical.phi) * k;
      this.spherical.radius += (t.dist - this.spherical.radius) * k;
      this.camera.position.setFromSpherical(this.spherical).add(this.controls.target);
      if (Math.abs(dAz) < 0.002 && Math.abs(t.dist - this.spherical.radius) < 0.005)
        this.camTarget = null;
    }
    this.controls?.update();

    if (this.active && this.progress < 1) {
      this.progress = Math.min(1, this.progress + dt / 1.2);
      this.applyProgress();
    }

    // traveling glow along the active tape
    if (this.active && !this.opts.reducedMotion) {
      const pts = this.active.points;
      const time = this.clock.getElapsed();
      const along = this.progress < 1 ? this.progress : (time * 0.35) % 1;
      const f = along * (pts.length - 1);
      const i = Math.floor(f);
      this.pulse.position.lerpVectors(pts[i], pts[Math.min(pts.length - 1, i + 1)], f - i);
      this.pulse.visible = true;
      (this.pulse.material as THREE.SpriteMaterial).opacity = 0.6 + 0.4 * Math.sin(time * 6);
    } else if (this.pulse) {
      this.pulse.visible = false;
    }

    this.renderer.render(this.scene, this.camera);
    this.emitLabel();
  }

  private emitLabel(): void {
    if (!this.onLabel || !this.active) return;
    const p = this.tmp.copy(this.active.anchor).project(this.camera);
    const toCam = this.camera.position.clone().sub(this.active.anchor).normalize();
    const facing = toCam.dot(this.active.anchorNormal) > -0.1;
    const el = this.canvas;
    this.onLabel({
      x: ((p.x + 1) / 2) * el.clientWidth,
      y: ((1 - p.y) / 2) * el.clientHeight,
      visible: facing && this.progress > 0.6 && p.z < 1,
    });
  }

  dispose(): void {
    this.stop();
    this.resizeObserver?.disconnect();
    this.controls?.dispose();
    disposeObject(this.scene);
    this.envTex?.dispose();
    this.pmrem?.dispose();
    this.renderer.dispose();
    this.renderer.forceContextLoss();
  }
}
